def digest(data):
    return hashlib.sha256(data).hexdigest()

def read_source(path):
    return path.read_text(encoding="utf-8-sig").encode("utf-8")

def load_manifest():
    raw = lzma.decompress(base64.b64decode(PAYLOAD))
    if digest(raw) != PAYLOAD_SHA256:
        raise ValueError("Incomplete payload: copy the whole script again.")
    manifest = json.loads(raw)
    if manifest.get("schema") != 1:
        raise ValueError("Unsupported source format.")
    return manifest["files"]

def make_plan(project, manifest):
    if not (project / "pubspec.yaml").is_file():
        raise ValueError("Select the existing Flutter folder containing pubspec.yaml.")
    plan, failures = {}, []
    for name, spec in manifest.items():
        relative = PurePosixPath(name)
        path = project.joinpath(*relative.parts)
        if relative.is_absolute() or ".." in relative.parts or not path.resolve().is_relative_to(project):
            raise ValueError("Invalid source path: " + name)
        current = read_source(path) if path.is_file() else None
        actual = None if current is None else digest(current)
        if actual == spec["new"]:
            plan[name] = (path, current, False)
            continue
        if actual != spec["old"]:
            failures.append(name)
            continue
        lines = [] if current is None else current.decode("utf-8").splitlines(keepends=True)
        last_end = 0
        for start, end, text in spec["edits"]:
            if not (last_end <= start <= end <= len(lines)) or not isinstance(text, str):
                raise ValueError("Invalid source edits: " + name)
            last_end = end
        for start, end, text in reversed(spec["edits"]):
            lines[start:end] = text.splitlines(keepends=True)
        updated = "".join(lines).encode("utf-8")
        if digest(updated) != spec["new"]:
            raise ValueError("Source reconstruction checksum failed: " + name)
        plan[name] = (path, updated, True)
    if failures:
        raise ValueError("No source files changed. These files differ from the verified branch:\n"
                         + "\n".join(failures))
    return plan

def atomic_write(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    handle = tempfile.NamedTemporaryFile(dir=path.parent, delete=False)
    temporary = Path(handle.name)
    try:
        with handle:
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)

def apply_plan(plan):
    originals, installed = {}, []
    for name, (path, data, changed) in plan.items():
        if not changed:
            continue
        originals[name] = path.read_bytes() if path.is_file() else None
        if originals[name] is not None:
            backup = path.with_name(path.name + ".before-market-scan-fix")
            if backup.exists() and backup.read_bytes() != originals[name]:
                raise ValueError("Different backup already exists: " + str(backup))
            if not backup.exists():
                shutil.copy2(path, backup)
    try:
        for name, (path, data, changed) in plan.items():
            if changed:
                atomic_write(path, data)
                installed.append(name)
    except Exception:
        for name in reversed(installed):
            if originals[name] is None:
                plan[name][0].unlink(missing_ok=True)
            else:
                atomic_write(plan[name][0], originals[name])
        raise
    for name, (_, _, changed) in plan.items():
        print(("UPDATED " if changed else "ALREADY CURRENT ") + name)

def export_zip(project, plan, output):
    output.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(output, "w", zipfile.ZIP_DEFLATED) as archive:
        for name, (_, data, _) in plan.items():
            archive.writestr(name, data)
        archive.write(Path(__file__).resolve(), "scripts/apply_market_scan_fix.py")
        workflow = project / ".github/workflows/build_apk.yml"
        if workflow.is_file():
            archive.write(workflow, ".github/workflows/build_apk.yml")
        archive.writestr("README_MARKET_SCAN_FIX.txt",
            "Updated files for the existing Flutter project. Core pool30; batch5; delay150ms.\n"
            "HTTP8s; market scan60s; controller70s; quotes/holdings8s.\n"
            "Run flutter pub get, flutter analyze and flutter test.\n"
            "Live recommendation gate must pass before APK build.\n")
    with zipfile.ZipFile(output) as archive:
        if archive.testzip() is not None:
            raise ValueError("ZIP integrity failed.")
    print("SOURCE ZIP: " + str(output))
    print("ZIP SHA256: " + digest(output.read_bytes()))

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project", type=Path, default=Path.cwd())
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--show", help="Print one complete updated file without writing")
    parser.add_argument("--zip", dest="zip_path", type=Path)
    args = parser.parse_args()
    project = args.project.resolve()
    plan = make_plan(project, load_manifest())
    if args.show:
        if args.show not in plan:
            raise ValueError("Unknown source file: " + args.show)
        sys.stdout.write(plan[args.show][1].decode("utf-8"))
    elif args.check:
        for name in plan:
            print("VERIFIED " + name)
    else:
        apply_plan(plan)
        if args.zip_path:
            output = args.zip_path if args.zip_path.is_absolute() else project / args.zip_path
            export_zip(project, plan, output)

if __name__ == "__main__":
    try:
        main()
    except Exception as error:
        print("ERROR: " + str(error), file=sys.stderr)
        sys.exit(1)
